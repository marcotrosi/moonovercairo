cairo = require "moc"

local S = cairo.image_surface_create(cairo.FORMAT_RGB24, 300, 300)
local C = cairo.create(S)

cairo.set_source_rgb(C, 1.0, 1.0, 1.0)
cairo.rectangle(C, 100, 100, 100, 100)
cairo.stroke(C)
cairo.move_to(C, 100, 100)
cairo.line_to(C, 150, 150)
cairo.stroke(C)
cairo.move_to(C, 200, 100)
cairo.line_to(C, 250, 150)
cairo.stroke(C)
cairo.move_to(C, 100, 200)
cairo.line_to(C, 150, 250)
cairo.stroke(C)
cairo.set_source_rgb(C, 0.2, 0.5, 1.0)
cairo.rectangle(C, 150, 150, 100, 100)
cairo.fill(C)
cairo.set_source_rgb(C, 1.0, 1.0, 1.0)
cairo.rectangle(C, 150, 150, 100, 100)
cairo.stroke(C)
cairo.surface_write_to_png(S, "foo.png")
cairo.surface_destroy(S)
cairo.destroy(C)
