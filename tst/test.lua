moc = require "moc"

local S = moc.image_surface_create(0, 300, 300)
local C = moc.create(S)

moc.set_source_rgb(C, 1.0, 1.0, 1.0)
moc.rectangle(C, 100, 100, 100, 100)
moc.stroke(C)
moc.move_to(C, 100, 100)
moc.line_to(C, 150, 150)
moc.stroke(C)
moc.move_to(C, 200, 100)
moc.line_to(C, 250, 150)
moc.stroke(C)
moc.move_to(C, 100, 200)
moc.line_to(C, 150, 250)
moc.stroke(C)
moc.set_source_rgb(C, 0.2, 0.5, 1.0)
moc.rectangle(C, 150, 150, 100, 100)
moc.fill(C)
moc.set_source_rgb(C, 1.0, 1.0, 1.0)
moc.rectangle(C, 150, 150, 100, 100)
moc.stroke(C)
moc.surface_write_to_png(S, "foo.png")
moc.surface_destroy(S)
moc.destroy(C)
